pub struct FieldHandle {
    element: Element,
}

impl Clone for FieldHandle {
    fn clone(&self) -> Self {
        Self {
            element: self.element.retained(),
        }
    }
}

impl std::fmt::Debug for FieldHandle {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("FieldHandle(ax)")
    }
}

/// Apps that were asked to build their accessibility tree. Electron and Chromium only build it when asked,
/// and asynchronously, so the first request is made as early as possible and only once per process.
static ENABLED_PIDS: Mutex<Option<HashSet<i32>>> = Mutex::new(None);

fn enable_accessibility_tree(pid: i32, app: &Element) -> bool {
    let mut enabled = ENABLED_PIDS.lock().expect("pid set");
    let set = enabled.get_or_insert_with(HashSet::new);
    if set.insert(pid) {
        app.set(
            "AXManualAccessibility",
            CFBoolean::true_value().as_CFTypeRef(),
        );
        return true;
    }
    false
}

fn frontmost_pid() -> Option<i32> {
    autoreleasepool(|_| {
        let workspace = unsafe { NSWorkspace::sharedWorkspace() };
        unsafe { workspace.frontmostApplication() }.map(|app| unsafe { app.processIdentifier() })
    })
}

pub fn focus() -> Focus {
    let mut focus = Focus::default();
    let Some(pid) = frontmost_pid() else {
        return focus;
    };
    let app = Element::application(pid);
    let just_enabled = enable_accessibility_tree(pid, &app);
    focus.app = app_context(pid, &app);

    // A tree that was just requested may need a moment to appear.
    let attempts = if just_enabled { 4 } else { 1 };
    let mut element = None;
    for attempt in 0..attempts {
        match app.element(kAXFocusedUIElementAttribute) {
            Ok(Some(found)) => {
                element = Some(found);
                break;
            }
            Ok(None) if attempt + 1 < attempts => {
                std::thread::sleep(std::time::Duration::from_millis(50))
            }
            Ok(None) => {}
            Err(Unresponsive) => return focus,
        }
    }
    // Some apps only answer the system-wide query.
    let element = element.or_else(|| {
        Element::system_wide()
            .element(kAXFocusedUIElementAttribute)
            .ok()
            .flatten()
    });
    let Some(element) = element else { return focus };
    let field = FieldHandle { element };
    focus.info = field.info();
    if !focus.info.is_secure {
        focus.state = field.read().unwrap_or_default();
    }
    focus.field = Some(field);
    focus
}

fn app_context(pid: i32, app: &Element) -> AppContext {
    let (app_name, app_id) = autoreleasepool(|_| {
        let running = unsafe { NSRunningApplication::runningApplicationWithProcessIdentifier(pid) };
        (
            running
                .as_ref()
                .and_then(|r| unsafe { r.localizedName() })
                .map(|s| s.to_string()),
            running
                .as_ref()
                .and_then(|r| unsafe { r.bundleIdentifier() })
                .map(|s| s.to_string()),
        )
    });
    let window_title = app
        .element(kAXFocusedWindowAttribute)
        .ok()
        .flatten()
        .and_then(|w| w.string(kAXTitleAttribute).ok().flatten());
    AppContext {
        app_name,
        app_id,
        pid: Some(pid),
        window_title,
        is_elevated: false,
    }
}

impl FieldHandle {
    fn info(&self) -> FieldInfo {
        let role = self.element.string(kAXRoleAttribute).ok().flatten();
        let subrole = self.element.string(kAXSubroleAttribute).ok().flatten();
        FieldInfo {
            is_secure: subrole.as_deref() == Some(kAXSecureTextFieldSubrole)
                || secure_input_active(),
            role: match subrole {
                Some(sub) => role.map(|r| format!("{r}/{sub}")),
                None => role,
            },
        }
    }

    pub fn read(&self) -> Result<FieldState> {
        if secure_input_active() {
            bail!("secure input is active");
        }
        let read = || -> Result<FieldState, Unresponsive> {
            if self.element.string(kAXSubroleAttribute)?.as_deref()
                == Some(kAXSecureTextFieldSubrole)
            {
                return Ok(FieldState::default());
            }
            Ok(FieldState {
                text: self.element.string(kAXValueAttribute)?,
                selection: self.element.range(kAXSelectedTextRangeAttribute)?,
                selected_text: self.element.string(kAXSelectedTextAttribute)?,
            })
        };
        read().map_err(|_| anyhow!("the app is not responding to accessibility requests"))
    }

    /// Selects `expected` at UTF-16 offset `start` (AX ranges are UTF-16), verifying it first.
    pub fn select(&self, start: usize, expected: &str) -> Result<()> {
        let text = self
            .read()?
            .text
            .ok_or_else(|| anyhow!("field text is not readable"))?;
        let units: Vec<u16> = text.encode_utf16().collect();
        let want: Vec<u16> = expected.encode_utf16().collect();
        let at = |s: usize| units.get(s..s + want.len()) == Some(&want[..]);
        let start = if at(start) {
            start
        } else {
            (0..units.len().saturating_sub(want.len()) + 1)
                .filter(|&s| at(s))
                .min_by_key(|s| s.abs_diff(start))
                .ok_or_else(|| anyhow!("the text to replace is no longer in the field"))?
        };
        let range = CFRangeRaw {
            location: start as isize,
            length: want.len() as isize,
        };
        let value =
            unsafe { AXValueCreate(kAXValueTypeCFRange, &range as *const _ as *const c_void) };
        if value.is_null() {
            bail!("AXValueCreate failed");
        }
        let ok = self
            .element
            .set(kAXSelectedTextRangeAttribute, value as CFTypeRef);
        unsafe { CFRelease(value as CFTypeRef) };
        if ok {
            Ok(())
        } else {
            Err(anyhow!("the field rejected the selection change"))
        }
    }

    pub fn is_focused(&self) -> bool {
        Element::system_wide()
            .element(kAXFocusedUIElementAttribute)
            .ok()
            .flatten()
            .map(|focused| unsafe {
                CFEqual(focused.0 as CFTypeRef, self.element.0 as CFTypeRef) != 0
            })
            .unwrap_or(false)
    }
}

