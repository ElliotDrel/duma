fn pasteboard() -> Retained<NSPasteboard> {
    unsafe { NSPasteboard::generalPasteboard() }
}

/// Every item and type on the general pasteboard, except file promises (resolving them is slow and has side effects).
pub struct ClipboardSnapshot {
    items: Vec<Vec<(String, Vec<u8>)>>,
}

impl ClipboardSnapshot {
    pub fn capture() -> Result<Self> {
        autoreleasepool(|_| {
            let started = std::time::Instant::now();
            let mut total = 0usize;
            let mut items = Vec::new();
            if let Some(pasteboard_items) = unsafe { pasteboard().pasteboardItems() } {
                for item in pasteboard_items.iter() {
                    let mut entries = Vec::new();
                    for kind in unsafe { item.types() }.iter() {
                        let name = kind.to_string();
                        if name.contains("promise") {
                            continue;
                        }
                        if started.elapsed().as_millis() > 250 || total > 64 * 1024 * 1024 {
                            bail!("clipboard too large to back up ({total} bytes)");
                        }
                        if let Some(data) = unsafe { item.dataForType(&kind) } {
                            let bytes = data.to_vec();
                            total += bytes.len();
                            entries.push((name, bytes));
                        }
                    }
                    items.push(entries);
                }
            }
            Ok(Self { items })
        })
    }

    pub fn format_count(&self) -> usize {
        self.items.iter().map(Vec::len).sum()
    }

    pub fn restore(&self) -> Result<()> {
        autoreleasepool(|_| {
            let board = pasteboard();
            unsafe { board.clearContents() };
            if self.items.is_empty() {
                return Ok(());
            }
            let mut objects = Vec::new();
            for entries in &self.items {
                let item = unsafe { NSPasteboardItem::new() };
                for (kind, bytes) in entries {
                    let data = NSData::with_bytes(bytes);
                    unsafe { item.setData_forType(&data, &NSString::from_str(kind)) };
                }
                objects.push(ProtocolObject::from_retained(item));
            }
            let array = NSArray::from_retained_slice(&objects);
            if unsafe { board.writeObjects(&array) } {
                Ok(())
            } else {
                Err(anyhow!("writing the clipboard failed"))
            }
        })
    }
}

pub fn clipboard_sequence() -> u64 {
    autoreleasepool(|_| unsafe { pasteboard().changeCount() as u64 })
}

pub fn clipboard_text() -> Option<String> {
    autoreleasepool(|_| {
        unsafe { pasteboard().stringForType(NSPasteboardTypeString) }.map(|s| s.to_string())
    })
}

/// Writes Duma's temporary text, marked transient so clipboard managers skip it.
pub fn set_clipboard_text(text: &str) -> Result<()> {
    autoreleasepool(|_| {
        let board = pasteboard();
        unsafe { board.clearContents() };
        let item = unsafe { NSPasteboardItem::new() };
        unsafe { item.setString_forType(&NSString::from_str(text), NSPasteboardTypeString) };
        let empty = NSData::new();
        for kind in TRANSIENT_TYPES {
            unsafe { item.setData_forType(&empty, &NSString::from_str(kind)) };
        }
        let array = NSArray::from_retained_slice(&[ProtocolObject::from_retained(item)]);
        if unsafe { board.writeObjects(&array) } {
            Ok(())
        } else {
            Err(anyhow!("writing the clipboard failed"))
        }
    })
}
