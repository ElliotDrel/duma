pub fn modifiers_down() -> bool {
    let flags = unsafe { CGEventSourceFlagsState(HID_SYSTEM_STATE) };
    flags & (FLAG_SHIFT | FLAG_CONTROL | FLAG_OPTION | FLAG_COMMAND) != 0
}

/// Sends Cmd+<letter>. Fails without Accessibility trust, where macOS would drop it silently.
pub fn send_shortcut(letter: char) -> Result<()> {
    if !accessibility_trusted() {
        bail!("Duma needs Accessibility permission to paste");
    }
    let key = match letter {
        'v' => KEY_V,
        'c' => KEY_C,
        _ => bail!("unsupported shortcut letter {letter}"),
    };
    unsafe {
        let source = CGEventSourceCreate(HID_SYSTEM_STATE);
        if !source.is_null() {
            CGEventSourceSetLocalEventsSuppressionInterval(source, 0.0);
        }
        for down in [true, false] {
            let event = CGEventCreateKeyboardEvent(source, key, down);
            if event.is_null() {
                bail!("CGEventCreateKeyboardEvent failed");
            }
            CGEventSetFlags(event, FLAG_COMMAND);
            CGEventSetIntegerValueField(
                event,
                EVENT_SOURCE_USER_DATA,
                crate::INJECTED_MARKER as i64,
            );
            CGEventPost(HID_EVENT_TAP, event);
            CFRelease(event as CFTypeRef);
            if down {
                std::thread::sleep(std::time::Duration::from_millis(4));
            }
        }
        if !source.is_null() {
            CFRelease(source as CFTypeRef);
        }
    }
    Ok(())
}

