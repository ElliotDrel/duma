/// An owned AXUIElementRef.
struct Element(AXUIElementRef);

unsafe impl Send for Element {}
unsafe impl Sync for Element {}

impl Drop for Element {
    fn drop(&mut self) {
        unsafe { CFRelease(self.0 as CFTypeRef) };
    }
}

/// The target app is not answering; stop making AX calls for this operation.
#[derive(Debug)]
struct Unresponsive;

impl Element {
    fn system_wide() -> Self {
        let element = Self(unsafe { AXUIElementCreateSystemWide() });
        unsafe { AXUIElementSetMessagingTimeout(element.0, AX_TIMEOUT_SECONDS) };
        element
    }

    fn application(pid: i32) -> Self {
        let element = Self(unsafe { AXUIElementCreateApplication(pid) });
        unsafe { AXUIElementSetMessagingTimeout(element.0, AX_TIMEOUT_SECONDS) };
        element
    }

    /// Copies an attribute; the caller owns the result.
    fn copy(&self, attribute: &str) -> Result<Option<CFTypeRef>, Unresponsive> {
        let name = CFString::new(attribute);
        let mut value: CFTypeRef = std::ptr::null();
        let error = unsafe {
            AXUIElementCopyAttributeValue(self.0, name.as_concrete_TypeRef(), &mut value)
        };
        if error == kAXErrorCannotComplete {
            return Err(Unresponsive);
        }
        Ok((error == kAXErrorSuccess && !value.is_null()).then_some(value))
    }

    /// Copies an attribute only if it has the expected CF type.
    fn copy_typed(
        &self,
        attribute: &str,
        type_id: usize,
    ) -> Result<Option<CFTypeRef>, Unresponsive> {
        Ok(self.copy(attribute)?.and_then(|value| unsafe {
            if CFGetTypeID(value) as usize == type_id {
                Some(value)
            } else {
                CFRelease(value);
                None
            }
        }))
    }

    fn element(&self, attribute: &str) -> Result<Option<Element>, Unresponsive> {
        let type_id = unsafe { AXUIElementGetTypeID() } as usize;
        Ok(self
            .copy_typed(attribute, type_id)?
            .map(|v| Element(v as AXUIElementRef)))
    }

    fn string(&self, attribute: &str) -> Result<Option<String>, Unresponsive> {
        let type_id = unsafe { CFStringGetTypeID() } as usize;
        Ok(self
            .copy_typed(attribute, type_id)?
            .map(|v| unsafe { CFString::wrap_under_create_rule(v as CFStringRef) }.to_string()))
    }

    fn range(&self, attribute: &str) -> Result<Option<(usize, usize)>, Unresponsive> {
        let type_id = unsafe { AXValueGetTypeID() } as usize;
        let Some(value) = self.copy_typed(attribute, type_id)? else {
            return Ok(None);
        };
        let mut range = CFRangeRaw {
            location: 0,
            length: 0,
        };
        let ok = unsafe {
            AXValueGetValue(
                value as AXValueRef,
                kAXValueTypeCFRange,
                &mut range as *mut _ as *mut c_void,
            )
        };
        unsafe { CFRelease(value) };
        Ok((ok && range.location >= 0 && range.length >= 0)
            .then_some((range.location as usize, range.length as usize)))
    }

    fn set(&self, attribute: &str, value: CFTypeRef) -> bool {
        let name = CFString::new(attribute);
        unsafe {
            AXUIElementSetAttributeValue(self.0, name.as_concrete_TypeRef(), value)
                == kAXErrorSuccess
        }
    }

    fn retained(&self) -> Element {
        Element(unsafe { CFRetain(self.0 as CFTypeRef) } as AXUIElementRef)
    }
}

#[repr(C)]
struct CFRangeRaw {
    location: isize,
    length: isize,
}

