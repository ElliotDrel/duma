const HID_SYSTEM_STATE: i32 = 1;
const HID_EVENT_TAP: u32 = 0;
const FLAG_SHIFT: u64 = 0x0002_0000;
const FLAG_CONTROL: u64 = 0x0004_0000;
const FLAG_OPTION: u64 = 0x0008_0000;
const FLAG_COMMAND: u64 = 0x0010_0000;
/// ANSI key codes. Physical positions: correct for QWERTY-family layouts.
const KEY_C: u16 = 8;
const KEY_V: u16 = 9;
/// AX calls into a hung app otherwise block for up to six seconds.
const AX_TIMEOUT_SECONDS: f32 = 0.5;
/// Markers that tell clipboard managers to ignore Duma's temporary text (nspasteboard.org).
const TRANSIENT_TYPES: [&str; 2] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

#[link(name = "CoreGraphics", kind = "framework")]
